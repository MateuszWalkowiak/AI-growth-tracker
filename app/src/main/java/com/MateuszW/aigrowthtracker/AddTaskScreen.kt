package com.MateuszW.aigrowthtracker

import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.text.KeyboardOptions
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.input.KeyboardType
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AddTaskScreen(
    onSaveClick: () -> Unit,
    onCancelClick: () -> Unit
) {
    var taskName by remember { mutableStateOf("") }
    var duration by remember { mutableStateOf("") }
    var isMandatory by remember { mutableStateOf(false) }

    //opcje asystenta AI
    var isAIGenerated by remember { mutableStateOf(false) }
    var currentLevel by remember { mutableStateOf("") }
    var goals by remember { mutableStateOf("") }

    var selectedCategory by remember { mutableStateOf(TaskCategory.SPORT) } //TO DO

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Dodaj nowe zadanie") },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.primaryContainer
                )
            )
        }
    ) { paddingValues ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(paddingValues)
                .padding(16.dp)
                .verticalScroll(rememberScrollState()),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {

            //nazwa zadania
            OutlinedTextField(
                value = taskName,
                onValueChange = { taskName = it },
                label = { Text("Nazwa zadania") },
                modifier = Modifier.fillMaxWidth()
            )
            //wybór kategorii
            Text("Kategoria:", fontWeight = FontWeight.Bold)
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceEvenly
            ) {
                TaskCategory.values().take(3).forEach { category ->
                    FilterChip(
                        selected = (selectedCategory == category),
                        onClick = { selectedCategory = category },
                        label = { Text(category.displayName) }
                    )
                }
            }
            //czas na zadnie
            OutlinedTextField(
                value = duration,
                onValueChange = { duration = it },
                label = { Text("Ile czasu chesz poświęcić na zadnie") },
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                modifier = Modifier.fillMaxWidth()
            )

            //czy zadanie obowiązkowe
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Column {
                    Text("Zadanie obowiązkowe?", fontWeight = FontWeight.Bold)
                    Text("Musisz je wykonać, by zaliczyć dzień", fontSize = 12.sp)
                }
                Switch(
                    checked = isMandatory,
                    onCheckedChange = { isMandatory = it }
                )
            }

            Divider(modifier = Modifier.padding(vertical = 8.dp))

            //obsługa zadania przez asystenta
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Column(modifier = Modifier.weight(1f)) {
                    Text("Zadanie sugerowane przez AI", fontWeight = FontWeight.Bold, color = MaterialTheme.colorScheme.primary)
                    Text("Gemini wymyśli dla Ciebie konkretne zadanie.", fontSize = 12.sp)
                }
                Switch(
                    checked = isAIGenerated,
                    onCheckedChange = { isAIGenerated = it }
                )
            }
            //sekcja promptowania asystenta
            if (isAIGenerated) {
                Card(
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Column(modifier = Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                        OutlinedTextField(
                            value = currentLevel,
                            onValueChange = { currentLevel = it },
                            label = { Text("Twój aktualny poziom (możesz opisać szczegółowo)") },
                            modifier = Modifier.fillMaxWidth()
                        )
                        OutlinedTextField(
                            value = goals,
                            onValueChange = { goals = it },
                            label = { Text("Twoje cele DŁUGOTERMINOWE") },
                            modifier = Modifier.fillMaxWidth()
                        )
                    }
                }
            }

            Spacer(modifier = Modifier.weight(1f))

            //zapisz/anuluj dodawanie zadania
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                OutlinedButton(onClick = onCancelClick, modifier = Modifier.weight(1f).padding(end = 8.dp)) {
                    Text("Anuluj")
                }
                Button(onClick = onSaveClick, modifier = Modifier.weight(1f).padding(start = 8.dp)) {
                    Text("Zapisz")
                }
            }
        }
    }
}