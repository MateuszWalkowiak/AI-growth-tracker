package com.MateuszW.aigrowthtracker

import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AddTaskScreen(
    onSaveClick: () -> Unit,
    onCancelClick: () -> Unit
) {
    val defaultCategories = listOf("Sport", "Umysł", "Zdrowie", "Kreatywność", "Inna")

    val predefinedTasks = mapOf(
        "Sport" to listOf("Bieganie (Śledzenie GPS)", "Siłownia", "Joga", "Inne"),
        "Umysł" to listOf("Zadania szachowe (Pobrane z lichess.com)", "Czytanie książki", "Programowanie", "Inne"),
        "Zdrowie" to listOf("Sen", "Spacer", "Medytacja", "Inne"),
        "Kreatywność" to listOf("Rysowanie", "Gra na instrumencie", "Pisanie dziennika", "Inne")
    )

    var categoryExpanded by remember { mutableStateOf(false) }
    var selectedCategory by remember { mutableStateOf(defaultCategories[0]) }
    var customCategory by remember { mutableStateOf("") }

    var taskExpanded by remember { mutableStateOf(false) }
    val currentTasksList = predefinedTasks[selectedCategory] ?: listOf("Własne zadanie")
    var selectedTask by remember { mutableStateOf(currentTasksList[0]) }
    var customTaskName by remember { mutableStateOf("") }

    var durationMinutes by remember { mutableFloatStateOf(30f) }

    var isMandatory by remember { mutableStateOf(false) }

    var isAIGenerated by remember { mutableStateOf(false) }
    var currentLevel by remember { mutableStateOf("") }
    var goals by remember { mutableStateOf("") }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Dodaj nowe zadanie") },
                colors = TopAppBarDefaults.topAppBarColors(containerColor = MaterialTheme.colorScheme.primaryContainer)
            )
        }
    ) { paddingValues ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(paddingValues)
                .padding(16.dp)
                .verticalScroll(rememberScrollState()),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {

            //wybór kategorii
            ExposedDropdownMenuBox(
                expanded = categoryExpanded,
                onExpandedChange = { categoryExpanded = !categoryExpanded }
            ) {
                OutlinedTextField(
                    value = selectedCategory,
                    onValueChange = {},
                    readOnly = true,
                    label = { Text("Kategoria") },
                    trailingIcon = { ExposedDropdownMenuDefaults.TrailingIcon(expanded = categoryExpanded) },
                    modifier = Modifier.menuAnchor().fillMaxWidth()
                )
                ExposedDropdownMenu(
                    expanded = categoryExpanded,
                    onDismissRequest = { categoryExpanded = false }
                ) {
                    defaultCategories.forEach { category ->
                        DropdownMenuItem(
                            text = { Text(category) },
                            onClick = {
                                selectedCategory = category
                                categoryExpanded = false
                                selectedTask = predefinedTasks[category]?.get(0) ?: "Inne"
                            }
                        )
                    }
                }
            }

            if (selectedCategory == "Inna") {
                OutlinedTextField(
                    value = customCategory,
                    onValueChange = { customCategory = it },
                    label = { Text("Wpisz nazwę swojej kategorii") },
                    modifier = Modifier.fillMaxWidth()
                )
            }

            //nazwa zadnia
            ExposedDropdownMenuBox(
                expanded = taskExpanded,
                onExpandedChange = { taskExpanded = !taskExpanded }
            ) {
                OutlinedTextField(
                    value = selectedTask,
                    onValueChange = {},
                    readOnly = true,
                    label = { Text("Zadanie") },
                    trailingIcon = { ExposedDropdownMenuDefaults.TrailingIcon(expanded = taskExpanded) },
                    modifier = Modifier.menuAnchor().fillMaxWidth()
                )
                ExposedDropdownMenu(
                    expanded = taskExpanded,
                    onDismissRequest = { taskExpanded = false }
                ) {
                    currentTasksList.forEach { task ->
                        DropdownMenuItem(
                            text = { Text(task) },
                            onClick = {
                                selectedTask = task
                                taskExpanded = false
                            }
                        )
                    }
                }
            }

            if (selectedTask == "Inne" || selectedCategory == "Inna") {
                OutlinedTextField(
                    value = customTaskName,
                    onValueChange = { customTaskName = it },
                    label = { Text("Wpisz nazwę zadania") },
                    modifier = Modifier.fillMaxWidth()
                )
            }

            Divider()

            //czas na zadnie
            Column(modifier = Modifier.fillMaxWidth()) {
                Text(
                    text = "Czas na zadanie: ${durationMinutes.toInt()} min",
                    fontWeight = FontWeight.Bold
                )
                Slider(
                    value = durationMinutes,
                    onValueChange = { durationMinutes = it },
                    valueRange = 5f..180f,
                    steps = 34 //5-180min z korkiem 5
                )
            }
            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween, verticalAlignment = Alignment.CenterVertically) {
                Text("Zadanie obowiązkowe?", fontWeight = FontWeight.Bold)
                Switch(checked = isMandatory, onCheckedChange = { isMandatory = it })
            }

            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween, verticalAlignment = Alignment.CenterVertically) {
                Text("Wsparcie AI", fontWeight = FontWeight.Bold, color = MaterialTheme.colorScheme.primary)
                Switch(checked = isAIGenerated, onCheckedChange = { isAIGenerated = it })
            }

            if (isAIGenerated) {
                Card(colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant)) {
                    Column(modifier = Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                        OutlinedTextField(value = currentLevel, onValueChange = { currentLevel = it }, label = { Text("Twój aktualny poziom (możesz opisać szczegółowo)") }, modifier = Modifier.fillMaxWidth())
                        OutlinedTextField(value = goals, onValueChange = { goals = it }, label = { Text("Twoje cel DŁUGOTERMINOWE") }, modifier = Modifier.fillMaxWidth())
                    }
                }
            }

            Spacer(modifier = Modifier.weight(1f))

            // 5. PRZYCISKI
            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                OutlinedButton(onClick = onCancelClick, modifier = Modifier.weight(1f).padding(end = 8.dp)) {
                    Text("Anuluj")
                }
                Button(onClick = onSaveClick, modifier = Modifier.weight(1f).padding(start = 8.dp)) {
                    Text("Zapisz")
                }
            }
        }
    }
}